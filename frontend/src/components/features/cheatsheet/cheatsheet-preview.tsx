'use client';

import React from 'react';
import ReactMarkdown from 'react-markdown';
import remarkMath from 'remark-math';
import rehypeKatex from 'rehype-katex';
import { cn } from '@/lib/utils';
import type { CheatSheetFormat } from '@/types';
import { Sparkles, BookOpen, Clock, FileText } from 'lucide-react';

export interface CheatSheetPreviewProps {
  content: string;
  format: CheatSheetFormat;
  title: string;
  subjectTitle?: string;
  date?: string;
  className?: string;
}

const formatBadges: Record<
  CheatSheetFormat,
  { label: string; icon: React.ComponentType<{ className?: string }>; color: string }
> = {
  one_page: {
    label: 'One-Page Summary',
    icon: FileText,
    color: 'bg-blue-500/10 text-blue-600 dark:text-blue-400 border-blue-500/20',
  },
  formulas_only: {
    label: 'Formulas Only',
    icon: BookOpen,
    color: 'bg-emerald-500/10 text-emerald-600 dark:text-emerald-400 border-emerald-500/20',
  },
  last_minute: {
    label: 'Last-Minute Revision',
    icon: Clock,
    color: 'bg-amber-500/10 text-amber-600 dark:text-amber-400 border-amber-500/20',
  },
};

export function CheatSheetPreview({
  content,
  format,
  title,
  subjectTitle,
  date,
  className,
}: CheatSheetPreviewProps) {
  const badge = formatBadges[format] || formatBadges.one_page;
  const BadgeIcon = badge.icon;

  return (
    <div
      id="cheatsheet-print-area"
      className={cn(
        'w-full rounded-xl border border-border bg-card p-6 sm:p-8 text-foreground shadow-sm transition-all',
        'print:border-none print:shadow-none print:p-0 print:m-0 print:bg-white print:text-black',
        className
      )}
    >
      {/* Document Header */}
      <div className="mb-6 border-b border-border/80 pb-4 print:border-b-2 print:border-neutral-800 print:pb-3">
        <div className="flex flex-wrap items-center justify-between gap-3">
          <div>
            <div className="flex items-center gap-2 mb-1">
              {subjectTitle && (
                <span className="text-xs font-semibold uppercase tracking-wider text-primary print:text-neutral-800">
                  {subjectTitle}
                </span>
              )}
              <span
                className={cn(
                  'inline-flex items-center gap-1 rounded-full px-2.5 py-0.5 text-[11px] font-semibold border print:border-neutral-400 print:bg-neutral-100 print:text-black',
                  badge.color
                )}
              >
                <BadgeIcon className="h-3 w-3" />
                {badge.label}
              </span>
            </div>
            <h1 className="text-xl sm:text-2xl font-black tracking-tight text-foreground print:text-2xl print:text-black">
              {title}
            </h1>
          </div>
          <div className="text-right text-xs text-muted-foreground print:text-neutral-600">
            <p>Generated by Student Life OS</p>
            <p>{date || new Date().toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' })}</p>
          </div>
        </div>
      </div>

      {/* Multi-column Dense Reference Layout */}
      <div
        className={cn(
          'columns-1 md:columns-2 gap-6 [column-fill:_balance]',
          'print:columns-2 print:gap-4 print:text-[11px]'
        )}
      >
        <ReactMarkdown
          remarkPlugins={[remarkMath]}
          rehypePlugins={[rehypeKatex]}
          components={{
            h1: ({ ...props }) => (
              <div className="break-after-avoid mb-2 mt-4 first:mt-0">
                <h1
                  className="text-base font-bold uppercase tracking-wide text-foreground border-b-2 border-primary/40 pb-1 print:border-neutral-800 print:text-black print:text-sm"
                  {...props}
                />
              </div>
            ),
            h2: ({ ...props }) => (
              <div className="break-after-avoid mb-2 mt-3 first:mt-0">
                <h2
                  className="flex items-center text-sm font-bold text-foreground border-l-4 border-primary pl-2 py-0.5 bg-primary/5 rounded-r print:bg-neutral-100 print:border-neutral-800 print:text-black print:text-xs"
                  {...props}
                />
              </div>
            ),
            h3: ({ ...props }) => (
              <h3
                className="break-after-avoid text-xs font-bold uppercase tracking-wider text-primary mt-2.5 mb-1 print:text-neutral-800"
                {...props}
              />
            ),
            p: ({ ...props }) => (
              <p
                className="text-xs text-foreground/90 leading-snug my-1 print:text-neutral-900 print:leading-tight"
                {...props}
              />
            ),
            strong: ({ ...props }) => (
              <strong
                className="font-bold text-foreground bg-primary/10 text-primary dark:text-primary-foreground px-1 py-0.5 rounded text-[0.95em] print:bg-neutral-200 print:text-black"
                {...props}
              />
            ),
            em: ({ ...props }) => (
              <em className="italic text-foreground/85 font-medium print:text-neutral-800" {...props} />
            ),
            ul: ({ ...props }) => (
              <ul
                className="list-disc list-inside space-y-0.5 my-1.5 pl-1 text-xs text-foreground/90 print:text-neutral-900"
                {...props}
              />
            ),
            ol: ({ ...props }) => (
              <ol
                className="list-decimal list-inside space-y-0.5 my-1.5 pl-1 text-xs text-foreground/90 print:text-neutral-900"
                {...props}
              />
            ),
            li: ({ ...props }) => (
              <li className="break-inside-avoid leading-tight" {...props} />
            ),
            blockquote: ({ ...props }) => (
              <div className="break-inside-avoid my-2">
                <blockquote
                  className="rounded-r-md border-l-3 border-amber-500 bg-amber-500/10 px-2.5 py-1.5 text-xs italic text-foreground print:border-neutral-700 print:bg-neutral-100 print:text-black"
                  {...props}
                />
              </div>
            ),
            // Highlighted Formula Box for LaTeX or code blocks
            pre: ({ ...props }) => (
              <div className="break-inside-avoid my-2 rounded-lg border border-primary/20 bg-primary/5 p-2 text-xs font-mono print:border-neutral-400 print:bg-neutral-100 print:text-black">
                <pre className="overflow-x-auto whitespace-pre-wrap" {...props} />
              </div>
            ),
            code: ({ inline, ...props }: { inline?: boolean } & React.HTMLAttributes<HTMLElement>) => {
              if (inline) {
                return (
                  <code
                    className="rounded bg-muted px-1 py-0.5 font-mono text-[0.85em] font-semibold text-primary dark:text-primary-foreground border border-border/40 print:border-neutral-300 print:bg-neutral-100 print:text-black"
                    {...props}
                  />
                );
              }
              return <code className="block" {...props} />;
            },
            table: ({ ...props }) => (
              <div className="break-inside-avoid overflow-x-auto my-2 w-full rounded border border-border print:border-neutral-400">
                <table className="w-full text-left border-collapse text-[11px] print:text-[10px]" {...props} />
              </div>
            ),
            thead: ({ ...props }) => (
              <thead className="bg-muted/80 text-foreground font-bold border-b border-border print:bg-neutral-200 print:text-black" {...props} />
            ),
            tbody: ({ ...props }) => (
              <tbody className="divide-y divide-border/60" {...props} />
            ),
            tr: ({ ...props }) => (
              <tr className="break-inside-avoid" {...props} />
            ),
            th: ({ ...props }) => (
              <th className="px-2 py-1 print:px-1.5 print:py-0.5" {...props} />
            ),
            td: ({ ...props }) => (
              <td className="px-2 py-1 print:px-1.5 print:py-0.5" {...props} />
            ),
            hr: () => (
              <hr className="my-2.5 border-dashed border-border/80 print:border-neutral-300" />
            ),
          }}
        >
          {content}
        </ReactMarkdown>
      </div>

      {/* Footer for Print Page */}
      <div className="mt-8 pt-3 border-t border-border/60 text-center text-[10px] text-muted-foreground hidden print:block print:text-neutral-500">
        Page 1 • Student Life OS Quick Reference Cheat Sheet
      </div>
    </div>
  );
}

export default CheatSheetPreview;
